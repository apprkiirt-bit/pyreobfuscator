import ast
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

from pyreobfuscator import builder

ROOT = pathlib.Path(__file__).resolve().parent
FIXTURE = ROOT / "fixtures" / "app"


class BuildTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory(prefix="pyreobfuscator-test-")
        cls.dir = pathlib.Path(cls.temp.name)
        cls.artifact = builder.build(builder.BuildOptions(
            path=str(FIXTURE),
            out=str(cls.dir / "app.py"),
        ))
        cls.plain = subprocess.run(
            [sys.executable, str(FIXTURE / "main.py")],
            capture_output=True, text=True,
        )
        cls.obf = subprocess.run(
            [sys.executable, str(cls.artifact)],
            capture_output=True, text=True,
        )

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def test_artifact_runs_and_matches(self):
        self.assertEqual(self.plain.returncode, 0, self.plain.stderr)
        self.assertEqual(self.obf.returncode, 0, self.obf.stderr)
        self.assertEqual(self.obf.stdout, self.plain.stdout)

    def test_no_plaintext_markers(self):
        source = self.artifact.read_text(encoding="utf-8")
        for marker in ("def bump", "def compute", "_hidden", "class Counter"):
            self.assertNotIn(marker, source)

    def test_no_markers_or_named_crypto(self):
        source = self.artifact.read_text(encoding="utf-8")
        for marker in ("PYREOBFUSCATOR-BEGIN", "PYREOBFUSCATOR-END",
                       "PYREOBFUSCATOR-HASH", "ChaCha20", "Poly1305",
                       "base64", "_MASK32", "_B64A", "def seal", "def kdf"):
            self.assertNotIn(marker, source)
        self.assertIn("# generated by pyreobfuscator", source)

    def test_no_source_blob_or_runtime_flags(self):
        source = self.artifact.read_text(encoding="utf-8")
        match = re.search(r"= (\{'manifest':.*?\})\n", source, re.S)
        self.assertIsNotNone(match)
        config = ast.literal_eval(match.group(1))
        self.assertNotIn("src", config)
        self.assertNotIn("checks", config)
        self.assertNotIn("source_fallback", source)
        self.assertIn("salt", config)

    def test_version_mismatch_is_rejected(self):
        wrapper = self.dir / "wrong_version.py"
        wrapper.write_text(
            "import runpy, sys\n"
            "sys.implementation.cache_tag = 'cpython-000'\n"
            "runpy.run_path(sys.argv[1], run_name='__main__')\n",
            encoding="utf-8",
        )
        proc = subprocess.run([sys.executable, str(wrapper), str(self.artifact)],
                              capture_output=True, text=True)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("SystemError", proc.stderr)

    def test_short_key_share_is_rejected(self):
        data = self.artifact.read_text(encoding="utf-8")
        tampered = re.sub(r"'share2': '[^']+'", "'share2': '00'", data, count=1)
        self.assertNotEqual(data, tampered)
        path = self.dir / "short_share.py"
        path.write_text(tampered, encoding="utf-8", newline="\n")
        proc = subprocess.run([sys.executable, str(path)], capture_output=True, text=True)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("SystemError", proc.stderr)

    def test_payload_never_uses_exec(self):
        artifact = builder.build(builder.BuildOptions(
            path=str(FIXTURE),
            out=str(self.dir / "noexec.py"),
            checks=False,
            selfhash=False,
        ))
        wrapper = self.dir / "spy.py"
        wrapper.write_text(
            "import builtins, sys, types\n"
            "artifact = sys.argv[1]\n"
            "source = open(artifact, 'rb').read()\n"
            "code = compile(source, artifact, 'exec')\n"
            "namespace = {'__name__': '__main__', '__file__': artifact, "
            "'__builtins__': builtins}\n"
            "seen = []\n"
            "original = builtins.exec\n"
            "def spy(payload, *args, **kwargs):\n"
            "    seen.append(getattr(payload, 'co_filename', '<source>'))\n"
            "    return original(payload, *args, **kwargs)\n"
            "builtins.exec = spy\n"
            "try:\n"
            "    types.FunctionType(code, namespace)()\n"
            "finally:\n"
            "    builtins.exec = original\n"
            "    print('PAYLOAD_HIT', [n for n in seen if n in ('main.py',)])\n",
            encoding="utf-8",
        )
        proc = subprocess.run([sys.executable, str(wrapper), str(artifact)],
                              capture_output=True, text=True)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("PAYLOAD_HIT []", proc.stdout)

    def test_tampered_loader_is_rejected(self):
        data = self.artifact.read_text(encoding="utf-8")
        tampered = data.replace("'h': '", "'h': '00", 1)
        path = self.dir / "tampered_hash.py"
        path.write_text(tampered, encoding="utf-8", newline="\n")
        proc = subprocess.run([sys.executable, str(path)], capture_output=True, text=True)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("SystemError", proc.stderr)

    def test_tampered_payload_is_rejected(self):
        data = self.artifact.read_text(encoding="utf-8")
        tampered = data.replace("internal error", "internal errox", 1)
        path = self.dir / "tampered_payload.py"
        path.write_text(tampered, encoding="utf-8", newline="\n")
        proc = subprocess.run([sys.executable, str(path)], capture_output=True, text=True)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("SystemError", proc.stderr)

    def test_trace_hook_is_rejected(self):
        wrapper = self.dir / "trace_spy.py"
        wrapper.write_text(
            "import sys, types\n"
            "artifact = sys.argv[1]\n"
            "sys.settrace(lambda *a: None)\n"
            "source = open(artifact, 'rb').read()\n"
            "code = compile(source, artifact, 'exec')\n"
            "namespace = {'__name__': '__main__', '__file__': artifact}\n"
            "try:\n"
            "    types.FunctionType(code, namespace)()\n"
            "except SystemError:\n"
            "    print('BLOCKED')\n",
            encoding="utf-8",
        )
        proc = subprocess.run([sys.executable, str(wrapper), str(self.artifact)],
                              capture_output=True, text=True)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("BLOCKED", proc.stdout)
        self.assertNotIn("counter", proc.stdout)


if __name__ == "__main__":
    unittest.main()
