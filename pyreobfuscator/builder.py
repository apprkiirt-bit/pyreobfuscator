"""Build pipeline: source tree -> single self-contained artifact."""

import ast
import builtins as _pybuiltins
import hashlib
import io
import keyword
import os
import random
import string
import sys
import tokenize
from dataclasses import dataclass
from pathlib import Path

from . import codec, crypto, passes, vm

_SKIP_DIRS = {"__pycache__", ".git", ".hg", ".svn", ".venv", "venv", "node_modules",
              "dist", "build", "out", "target"}


@dataclass
class BuildOptions:
    path: str
    out: str = ""
    entry: str = ""
    cff: str = "auto"
    vm: str = "auto"
    threshold: int = 0
    numbers: bool = False
    rename: bool = True
    rename_locals: bool = True
    checks: bool = True
    selfhash: bool = True
    antidebug: bool = True
    audit: bool = True
    strict_env: bool = True
    watchdog: float = 5.0
    seed: int = None


def _read_source(path):
    with tokenize.open(path) as handle:
        return handle.read()


def _module_name(root, path):
    parts = list(path.relative_to(root).with_suffix("").parts)
    if parts and parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def _collect_files(options):
    root = Path(options.path).resolve()
    if root.is_file():
        return root.parent, root, [root]
    if not root.is_dir():
        raise FileNotFoundError(root)
    entry = None
    if options.entry:
        entry = (root / options.entry).resolve()
    else:
        for candidate in ("main.py", "__main__.py"):
            path = root / candidate
            if path.is_file():
                entry = path
                break
        if entry is None:
            files = [p for p in root.rglob("*.py") if not _skip(p, root)]
            if len(files) == 1:
                entry = files[0]
    if entry is None or not entry.is_file():
        raise FileNotFoundError("entry module not found; pass --entry")
    files = []
    for path in sorted(root.rglob("*.py")):
        if _skip(path, root):
            continue
        files.append(path.resolve())
    if entry.resolve() not in files:
        files.append(entry.resolve())
    return root, entry.resolve(), files


def _skip(path, root):
    try:
        rel = path.relative_to(root)
    except ValueError:
        return True
    if any(part in _SKIP_DIRS or part.startswith(".") for part in rel.parts[:-1]):
        return True
    try:
        with open(path, "rb") as handle:
            head = handle.read(256)
    except OSError:
        return True
    return (b"#PYREOBFUSCATOR-BEGIN" in head or b"#PYREBFUSCATOR-BEGIN" in head
            or b"#PYOBF-BEGIN" in head
            or b"# generated by pyreobfuscator" in head
            or b"# generated by pyrebfuscator" in head
            or b"# generated by pyobf" in head)


def _entry_package(entry_name):
    if "." not in entry_name:
        return None
    parent = entry_name.rsplit(".", 1)[0]
    return parent or None


def _reserved_names(trees):
    reserved = set()
    for tree in trees.values():
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute):
                reserved.add(node.attr)
            elif isinstance(node, ast.ImportFrom):
                for alias in node.names:
                    reserved.add(alias.name)
            elif isinstance(node, ast.Constant) and isinstance(node.value, str):
                reserved.add(node.value)
    return reserved


def _random_token(rng, length=8):
    alphabet = string.ascii_lowercase + string.digits
    return "".join(rng.choice(alphabet) for _ in range(length))


def _seal(master, label, payload):
    return crypto.seal(crypto.kdf(master, label), payload, aad=label.encode())


def _opaque_name(rng, used):
    while True:
        name = rng.choice("Il") + "".join(
            rng.choice("Il1O0") for _ in range(rng.randint(7, 13)))
        if name not in used:
            used.add(name)
            return name


def _scramble_source(source, rng):
    tree = ast.parse(source)

    class Strip(ast.NodeTransformer):
        def _strip(self, node):
            self.generic_visit(node)
            body = getattr(node, "body", None)
            if isinstance(node, ast.Module):
                body[:] = [statement for statement in body
                           if not (isinstance(statement, ast.Expr)
                                   and isinstance(statement.value, ast.Constant)
                                   and isinstance(statement.value.value, str))]
            elif body and isinstance(body[0], ast.Expr) \
                    and isinstance(body[0].value, ast.Constant) \
                    and isinstance(body[0].value.value, str):
                body.pop(0)
            if body is not None and not body:
                node.body = [ast.Pass()]
            return node

        def visit_Module(self, node):
            return self._strip(node)

        def visit_FunctionDef(self, node):
            return self._strip(node)

        def visit_AsyncFunctionDef(self, node):
            return self._strip(node)

        def visit_ClassDef(self, node):
            return self._strip(node)

    tree = Strip().visit(tree)
    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                imported.add(alias.asname or alias.name.split(".")[0])
                imported.update(alias.name.split("."))
        elif isinstance(node, ast.ImportFrom):
            if node.module:
                imported.update(node.module.split("."))
            for alias in node.names:
                imported.add(alias.asname or alias.name)
    source = ast.unparse(tree)
    tokens = list(tokenize.generate_tokens(io.StringIO(source).readline))
    significant = (tokenize.NL, tokenize.NEWLINE, tokenize.INDENT,
                   tokenize.DEDENT, tokenize.COMMENT, tokenize.ENCODING)
    keywords = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            for keyword_node in node.keywords:
                if keyword_node.arg:
                    keywords.add(keyword_node.arg)
    reserved = set(keyword.kwlist) | set(dir(_pybuiltins)) | imported | keywords | {
        "find_spec", "exec_module", "create_module", "is_package",
        "module_repr", "get_data", "get_filename", "get_code", "get_source",
        "load_module", "path_mtime", "path_stats", "set_data", "invalidate_caches",
    }
    mapping = {}
    used = set(reserved)
    result = []
    previous = ""
    for token in tokens:
        if token.type == tokenize.NAME:
            name = token.string
            if name not in reserved and not name.startswith("__") \
                    and not name.endswith("__") and previous != ".":
                if name not in mapping:
                    mapping[name] = _opaque_name(rng, used)
                token = tokenize.TokenInfo(token.type, mapping[name], token.start,
                                           token.end, token.line)
        result.append(token)
        if token.type not in significant:
            previous = token.string
    return tokenize.untokenize(result), mapping


def build(options):
    rng = random.Random(options.seed) if options.seed is not None else random.Random()
    magic = os.urandom(3)
    codec._MAGIC = magic
    root, entry_path, files = _collect_files(options)
    entry_name = _module_name(root, entry_path)
    if not entry_name:
        raise ValueError("entry module has an empty name")

    modules = {}
    trees = {}
    for path in files:
        name = _module_name(root, path)
        if not name:
            continue
        if name in modules:
            raise ValueError("duplicate module name: %s" % name)
        modules[name] = path
        trees[name] = ast.parse(_read_source(path), filename=str(path.relative_to(root)).replace("\\", "/"))

    reserved = _reserved_names(trees)
    token = _random_token(rng)
    salt = _random_token(rng, 12)
    iter_name = "_%si" % token
    next_name = "_%sn" % token
    stop_name = "_%ss" % token
    vm_name = "_%sv" % token
    vm_ops = {}
    threshold = options.threshold or (1 if options.cff == "all" else 3)

    compiled = {}
    for index, (name, tree) in enumerate(trees.items()):
        passes.strip_docstrings(tree)
        if options.rename:
            passes.rename_private(tree, reserved=reserved, rng=rng)
        if options.rename and options.rename_locals:
            passes.rename_locals(tree, rng=rng)
        table_name = "_%st%d" % (token, index)
        programs = []
        vm.transform(tree, rng, vm_name, vm_ops, programs, mode=options.vm)
        pool = passes.ConstantPool()
        passes.encrypt_constants(tree, pool, table_name, rng, split_numbers=options.numbers)
        if options.cff != "off":
            passes.flatten(tree, threshold=threshold, rng=rng, iter_name=iter_name,
                           next_name=next_name, stop_name=stop_name,
                           skip_loops=(options.cff == "auto"))
        ast.fix_missing_locations(tree)
        filename = str(modules[name].relative_to(root)).replace("\\", "/")
        try:
            code = compile(tree, filename, "exec", dont_inherit=True)
        except SyntaxError as error:
            raise SyntaxError("%s: %s" % (name, error))
        compiled[name] = {
            "code": codec.dumps(code),
            "table": codec.dumps(tuple(pool.values)),
            "table_name": table_name,
            "vm": codec.dumps(programs) if programs else None,
            "file": filename,
            "pkg": modules[name].name == "__init__.py",
        }

    master = os.urandom(32)
    manifest_modules = {}
    for name, record in compiled.items():
        prefix = name + "|" + salt + "|"
        manifest_modules[name] = {
            "pkg": record["pkg"],
            "file": record["file"],
            "tag": sys.implementation.cache_tag,
            "table_name": record["table_name"],
            "code": _seal(master, prefix + "code", record["code"]),
            "table": _seal(master, prefix + "table", record["table"]),
            "vm": _seal(master, prefix + "vm", record["vm"]) if record["vm"] is not None else None,
        }

    manifest = {
        "version": list(sys.version_info[:2]),
        "cache_tag": sys.implementation.cache_tag,
        "salt": salt,
        "entry": entry_name,
        "entry_pkg": _entry_package(entry_name),
        "iter": iter_name,
        "next": next_name,
        "stop": stop_name,
        "vm": vm_name,
        "vm_ops": {index: name for name, index in vm_ops.items()},
        "modules": manifest_modules,
    }
    manifest_blob = crypto.seal(master, codec.dumps(manifest),
                                aad=("manifest|" + salt).encode())

    seed0 = os.urandom(16)
    seed1 = os.urandom(16)
    h0 = crypto.kdf(seed0, "share0")
    h1 = crypto.kdf(seed1, "share1")
    share2 = bytes(a ^ b ^ c for a, b, c in zip(master, h0, h1))

    config = {
        "manifest": manifest_blob.hex(),
        "share0": seed0.hex(),
        "share1": seed1.hex(),
        "share2": share2.hex(),
        "salt": salt,
        "thread": "t" + token,
        "watchdog": float(options.watchdog) if options.checks else 0.0,
        "message": "internal error",
        "h": "",
    }

    check_lines = []
    if options.checks:
        check_lines.extend([
            "    _pb_check_builtins()",
            "    _pb_check_trace()",
            "    _pb_check_meta()",
            "    _pb_check_modules()",
            "    _pb_check_env(%r)" % bool(options.strict_env),
        ])
        if options.audit:
            check_lines.append("    _pb_install_audit()")
        if options.selfhash:
            check_lines.append("    _pb_self_hash(cfg)")
        if options.antidebug:
            check_lines.append("    _pb_check_antidebug()")
    checks_block = "\n".join(check_lines) if check_lines else "    pass"

    base = Path(__file__).resolve().parent
    runtime_source = (base / "runtime.py").read_text(encoding="utf-8")
    runtime_source = runtime_source.replace("    # @@CORE_CHECKS@@", checks_block)
    combined = "\n\n".join([
        (base / "crypto.py").read_text(encoding="utf-8"),
        (base / "codec.py").read_text(encoding="utf-8"),
        runtime_source,
    ])
    combined = combined.replace('_MAGIC = b"PB1"', "_MAGIC = " + repr(magic))
    combined, mapping = _scramble_source(combined, rng)
    cfg_name = _opaque_name(rng, set(mapping.values()))
    main_name = mapping.get("_pb_main", "_pb_main")
    body = combined + "\n\n" + cfg_name + " = " + repr(config) + "\n" \
        + main_name + "(" + cfg_name + ")\n"
    text = "#!/usr/bin/env python3\n# generated by pyreobfuscator\n" + body
    placeholder = "'h': ''"
    index = text.rfind(placeholder)
    if index < 0:
        raise RuntimeError("hash placeholder missing")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    text = text[:index] + "'h': '" + digest + "'" + text[index + len(placeholder):]

    out = Path(options.out) if options.out else Path("dist") / (Path(options.path).stem + "_obf.py")
    out = out.resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "wb") as handle:
        handle.write(text.encode("utf-8"))
    return out
